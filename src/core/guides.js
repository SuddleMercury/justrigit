import { TARGETS } from './targets.js';

// Builds a beginner-friendly import guide for exactly what was exported.
export function buildGuide(doc, targetId, opts, names, processed, modeFor) {
  return buildGuideBody(doc, targetId, opts, names, processed, modeFor) + namingSection(doc, targetId, opts) + captureSection(names);
}

const NAMING_TEXT = {
  ue5: 'the **Unreal Engine 5 Mannequin** standard (`pelvis`, `spine_01`, `thigh_l`, `hand_r` …). Unreal\'s **IK Retargeter** recognises these names, so sharing animations with Manny, Quinn or MetaHumans needs almost no setup: right-click an animation → **Retarget Animations** → pick the target character → **Export Animations**.',
  mixamo: 'the **Mixamo** standard (`mixamorig:Hips`, `mixamorig:LeftUpLeg` …). Unity\'s **Humanoid** avatar maps it automatically (Rig tab → Animation Type: Humanoid → Apply), and Unreal, Godot and Blender retargeting tools recognise it too.',
  godot: 'Godot\'s **SkeletonProfileHumanoid** standard (`Hips`, `Spine`, `LeftUpperLeg`, `LeftLowerArm` …). In Godot: Advanced Import Settings → Skeleton3D → **Retarget → Bone Map → New BoneMap → SkeletonProfileHumanoid** — every bone matches by itself, so animations can be shared between any Godot humanoids. Unity Humanoid and VRM tools understand the same names.',
};

function namingSection(doc, targetId, opts) {
  const id = opts.naming || 'keep';
  const n = opts.namingMap ? opts.namingMap.size : 0;
  if (id === 'keep' || !NAMING_TEXT[id]) return `\n---\n\n## Bone names\n\nBone names were kept exactly as in your source file. Want a standard? Re-export with **Skeleton naming** set to Unreal, Mixamo or Godot.\n`;
  const sample = opts.namingMap ? [...opts.namingMap].slice(0, 6).map(([a, b]) => `\`${a}\` → \`${b}\``).join(', ') : '';
  return `\n---\n\n## Bone names (skeleton standard)\n\nThe skeleton in this file uses ${NAMING_TEXT[id]}\n\n${n ? `${n} bones were renamed for the export (e.g. ${sample}). Your project in JustRigIt keeps the original names.` : 'Your skeleton already used these names.'}\n`;
}

function captureSection(names) {
  const caps = names.clips.filter(({ clip }) => clip.userData && clip.userData.capture);
  if (!caps.length) return '';
  const rows = caps.map(({ clip, out }) => {
    const c = clip.userData.capture, fl = clip.userData.footLock;
    return `| \`${out}\` | ${c.video || '—'} | ${fl ? `${fl.skateBeforeCm} → ${fl.skateAfterCm} cm` : 'off'} |`;
  }).join('\n');
  return `\n---\n\n## Motion-captured animations\n\nThese clips were captured from video with JustRigIt Capture (NVIDIA GEM-X, running on your own PC). Foot locking pinned planted feet to the floor; the last column shows total foot sliding before → after.\n\n| Animation | Source video | Foot sliding |\n|---|---|---|\n${rows}\n\n> Video capture is an estimate. If a limb looks wrong where it was hidden from the camera in the video, re-film that part with the whole body in view.\n`;
}

function buildGuideBody(doc, targetId, opts, names, processed, modeFor) {
  const t = TARGETS[targetId];
  const clipLines = names.clips.map(({ clip, out }) => {
    const m = modeFor(clip);
    return `| \`${out}\` | ${(clip.duration).toFixed(2)} s | ${m === 'inplace' ? 'In place' : m === 'rootmotion' ? 'Root motion' : 'Unchanged'} |`;
  }).join('\n');
  const clipTable = names.clips.length
    ? `| Animation | Length | Movement |\n|---|---|---|\n${clipLines}`
    : '*No animations were included in this export.*';
  const anyRoot = names.clips.some(({ clip }) => modeFor(clip) === 'rootmotion');
  const file = opts.splitClips ? `${names.mesh}.glb` : `${names.mesh}.glb`;

  const header = `# Import guide — ${names.mesh} → ${t.label}

Generated by JustRigIt. Every step below matches the files in this download.

## What's in this download

- **\`${file}\`** — the character (mesh + skeleton${!opts.splitClips && names.clips.length ? ' + all animations' : ''}).
${opts.splitClips ? names.clips.map(({ out }) => `- **\`${out}.glb\`** — one animation each.`).join('\n') + '\n' : ''}- **\`justrigit-recipe.json\`** — a record of every step taken, so you (or an AI) can repeat this export exactly.
- **\`health-report.json\`** — the results of the health check.

${clipTable}

> **Format:** ${t.format}
> **Units:** ${t.unitsNote}
`;

  if (targetId === 'ue5' || targetId === 'ue4') {
    return header + `
---

## Part 1 — Import the character

**Step 1. Make a folder.** In the **Content Browser** (the file panel at the bottom of the Unreal editor), right-click → **New Folder** → name it \`Characters/${doc.baseName}\`.

> *Why:* Unreal creates several assets from one file (mesh, skeleton, physics, animations). A folder keeps them together.

**Step 2. Drag \`${file}\` into that folder.** An import options window opens.${targetId === 'ue4' ? ' (UE4: if nothing happens, enable **Edit → Plugins → glTF Importer** and restart the editor first.)' : ' In UE 5.4 and later this is the **Interchange** importer; the window title may say *Interchange Pipeline Configuration* or *Import Content*.'}

**Step 3. Check these settings** (names can vary slightly between Unreal versions):

| Setting | Set it to | Why |
|---|---|---|
| Import Skeletal Meshes | ✅ On | Brings in the character with its bones. |
| Skeleton | **None** | "None" means *create a new skeleton* for this character. |
| Import Animations | ✅ On | Brings in the animation clips. |
| Create Physics Asset | ✅ On | Gives the character simple collision shapes for ragdolls and hit detection. |

**Step 4. Click Import.** You should now see:

- \`${names.mesh}\` — the **Skeletal Mesh** (the character you place in levels).
- \`${names.mesh}_Skeleton\` (or similar) — the **Skeleton** asset, shared by all its animations.
- A **Physics Asset**, plus materials/textures.
${names.clips.length ? `- ${names.clips.map(({ out }) => `\`${out}\``).join(', ')} — **Animation Sequences**.` : ''}

**Step 5. Test it.** Double-click an animation sequence. It opens in the **Animation Editor** and plays. If the character is the right size and faces the right way, the import worked.

---

## Part 2 — Root motion${anyRoot ? '' : ' (not used in this export)'}

${anyRoot ? `Some animations in this export carry their forward movement on the \`root\` bone (**root motion**). Unreal ignores it until you switch it on:

1. Double-click the animation (e.g. \`${names.clips.find(({ clip }) => modeFor(clip) === 'rootmotion')?.out}\`).
2. In the **Asset Details** panel, find the **Root Motion** section.
3. Tick **Enable Root Motion**.
4. In your **Animation Blueprint**, click **Class Defaults** and set **Root Motion Mode** to **Root Motion from Everything** (or **from Montages Only** if you only play these through Montages).

> *When to use it:* attacks, dodges, vaults — moves where the character must travel an exact distance.
` : `All animations were exported **in place** (the character walks on the spot). That's what Unreal's standard **Character Movement Component** expects: your Blueprint moves the character, and the animation just plays on top. Nothing extra to set up.
`}
---

${blendSpaceSection(names, modeFor)}## ${blendSpaceSection(names, modeFor) ? 'Part 4' : 'Part 3'} — What's next

- **Play an animation from Blueprints:** in your Character Blueprint, select the **Mesh** component → **Details → Animation → Animation Mode: Use Animation Asset** → pick a sequence. Good for a quick test.
- **More animations:** add the *8-direction locomotion* pack in JustRigIt and re-export — this guide will then include a full Blend Space walkthrough.
- **Using Epic's mannequin animations on this character:** Unreal's **IK Retargeter** does this. The \`root\` bone added here makes that setup easier.
`;
  }

  if (targetId === 'godot') {
    const loops = names.clips.filter((c) => c.loop);
    return header + `
---

## Import into Godot 4

**Step 1. Copy the file in.** Put \`${file}\` into your project folder (e.g. \`res://characters/\`). Godot imports it automatically and builds a scene with a **Skeleton3D** (the bones) and an **AnimationPlayer** (the animations).

**Step 2. Check it.** Double-click the file in the **FileSystem** dock to open **Advanced Import Settings**. Pick an animation on the left and press play — the character should move.
${loops.length ? `
> **Looping is already set up.** ${loops.length} cycle animation${loops.length > 1 ? 's end' : ' ends'} in \`_loop\` (e.g. \`${loops[0].out}\`). Godot sees that word and switches looping on by itself. One-shot animations (jumps, gestures) don't loop.
` : ''}
**Step 3. Use it in a level.** Drag the \`.glb\` into your scene, or right-click it → **New Inherited Scene** to add your own nodes (collision shape, script) on top.

**Step 4. Make it face the right way in code.** Godot treats **+Z as a model's front**, which is how this character is exported. When you turn it with \`look_at()\`, pass \`true\` as the third argument so Godot uses the model's front:

\`\`\`
look_at(target_position, Vector3.UP, true)
\`\`\`

> Without that \`true\`, \`look_at\` aims the -Z side at the target and the character ends up facing away.
${anyRoot ? `
**Root motion:** on your **AnimationTree**, set **Root Motion Track** to \`Skeleton3D:root\`, then read it in your movement script with \`get_root_motion_position()\`.
` : ''}
**Sharing animations with other characters (optional).** JustRigIt has already baked the animations onto this character, so you don't need Godot's retargeting for them. If you later want to share animations with other characters inside Godot: select the Skeleton3D in Advanced Import Settings → **Retarget → Bone Map** → **New BoneMap** → profile **SkeletonProfileHumanoid**. Godot matches the bones automatically; any bone that stays red, assign by hand.
`;
  }

  if (targetId === 'unity') {
    return header + `
---

## Import into Unity

1. **Window → Package Manager** → **+** → **Add package by name** → \`com.unity.cloud.gltfast\` → **Add**. (One-time setup; this is Unity's official glTF importer.)
2. Drag \`${file}\` into your **Assets** folder.
3. Drag it into the scene. The animations appear as clips you can use in an **Animator Controller**.
${anyRoot ? '\n**Root motion:** on the **Animator** component, tick **Apply Root Motion**.\n' : ''}`;
  }

  return header + `
---

## Import into Blender

1. **File → Import → glTF 2.0 (.glb/.gltf)** → select \`${file}\`.
2. Each animation becomes an **Action**. Switch between them in the **Action Editor** (Dope Sheet → Action Editor dropdown).
`;
}

// Step-by-step 2D Blend Space + Animation Blueprint walkthrough (Blueprints only).
function blendSpaceSection(names, modeFor) {
  const loco = names.clips.filter(({ clip }) => clip.userData?.lib?.direction !== undefined && /^(Walk|Run)_/.test(clip.userData.lib.id));
  if (loco.length < 4) return '';
  const idle = names.clips.find(({ clip }) => clip.userData?.lib?.id === 'Idle');
  const rows = loco.map(({ clip, out }) => {
    const l = clip.userData.lib;
    return `| \`${out}\` | ${Math.abs(l.direction) === 180 ? '-180 **and** 180' : l.direction} | ${Math.round(l.speed * 100)} |`;
  }).join('\n');
  const maxSpeed = Math.max(...loco.map(({ clip }) => clip.userData.lib.speed)) * 100;
  const walkFwd = loco.find(({ clip }) => clip.userData.lib.id === 'Walk_Fwd');
  const runFwd = loco.find(({ clip }) => clip.userData.lib.id === 'Run_Fwd');
  const anyRoot = loco.some(({ clip }) => modeFor(clip) === 'rootmotion');
  return `
---

## Part 3 — 8-direction movement with a Blend Space

A **Blend Space** mixes animations based on two numbers. We'll use **Direction** (which way the character moves compared to where it faces) and **Speed** (how fast). Unreal then blends smoothly between walk-forward, strafe-left, run-back-right and so on.
${anyRoot ? '\n> ⚠ Some of these clips were exported with **root motion**. Blend Spaces for player movement work best **in place** — re-export with *In place* selected if the character drifts.\n' : ''}
**Step 1. Create the Blend Space.** In the Content Browser, right-click → **Animation → Blend Space** (in UE4 and early UE5: **Blend Space** — not *Blend Space 1D*). Pick the skeleton \`${names.mesh}_Skeleton\`. Name it \`BS_${names.mesh.replace(/^SK_/, '')}_Locomotion\`.

**Step 2. Set up the two axes.** Open it. In the **Asset Details** panel, find **Axis Settings**:

| | Name | Minimum | Maximum |
|---|---|---|---|
| Horizontal Axis | \`Direction\` | -180 | 180 |
| Vertical Axis | \`Speed\` | 0 | ${Math.ceil(maxSpeed / 50) * 50} |

> *Why:* Direction is in degrees (0 = forward, 90 = right, -90 = left, ±180 = backwards). Speed is in Unreal units per second (centimeters per second).

**Step 3. Place the animations.** From the **Asset Browser** (bottom right), drag each animation onto the grid at these points (hold **Shift** while dragging to snap to the grid):

| Animation | Direction | Speed |
|---|---|---|
${idle ? `| \`${idle.out}\` | -180, -90, 0, 90 **and** 180 | 0 |\n` : ''}${rows}
${idle ? '\n> Put the idle at Speed 0 across the whole bottom edge so stopping blends smoothly from any direction.\n' : ''}${loco.some(({ clip }) => clip.userData.lib.id === 'Walk_Bwd') ? '\n> Backwards clips go at **both** -180 and 180 — those are the same direction, so the edges must match.\n' : ''}
Hold **Ctrl** and move the mouse over the grid to preview the blend.

**Step 4. Create an Animation Blueprint.** Right-click → **Animation → Animation Blueprint** → choose \`${names.mesh}_Skeleton\` → name it \`ABP_${names.mesh.replace(/^SK_/, '')}\`.

**Step 5. Make two variables.** In the **My Blueprint** panel → **Variables → +**: \`Speed\` (Float) and \`Direction\` (Float).

**Step 6. Fill them every frame (Event Graph).**
1. Start from **Event Blueprint Update Animation**.
2. Drag off **Try Get Pawn Owner** → **Is Valid** (the *? Is Valid* macro), so nothing runs before the character exists.
3. From the pawn: **Get Velocity** → **Vector Length XY** → **Set Speed**.
4. Add **Calculate Direction**: plug **Get Velocity** into *Velocity* and the pawn's **Get Actor Rotation** into *Base Rotation* → **Set Direction**.

> *Why "XY"?* It ignores up/down speed, so jumping or falling doesn't make the character run in the air.

**Step 7. Use the Blend Space (Anim Graph).** Open the **AnimGraph**, drag \`BS_${names.mesh.replace(/^SK_/, '')}_Locomotion\` in from the Asset Browser, connect **Speed** and **Direction** to its pins, and connect its output to **Output Pose**. Click **Compile**.

**Step 8. Hook it up to your character.** Open your Character Blueprint:
- Select the **Mesh** component → **Details → Animation**: Animation Mode **Use Animation Blueprint**, Anim Class \`ABP_${names.mesh.replace(/^SK_/, '')}\`.
- Select **Character Movement**: **Max Walk Speed** = ${walkFwd ? Math.round(walkFwd.clip.userData.lib.speed * 100) : 140} to walk${runFwd ? `, or ${Math.round(runFwd.clip.userData.lib.speed * 100)} to run (change it while Shift is held for sprinting)` : ''}. **Orient Rotation to Movement**: **off**.
- Click **Class Defaults** (top bar) → **Use Controller Rotation Yaw**: **on**.

> *Why the last two:* for strafing, the character must keep facing where the camera looks while it moves sideways or backwards. With *Orient Rotation to Movement* on, it would always turn to face its movement and you'd only ever see the forward animations.

Press **Play** and move with WASD — the character now blends between all eight directions.

`;
}
